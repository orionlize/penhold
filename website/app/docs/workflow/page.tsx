import { docMeta } from '../nav';
import { Code, DocHead, H2, Note, Table } from '../ui';

export const metadata = docMeta('workflow');

export default function Workflow() {
  return (
    <>
      <DocHead
        eyebrow="Docs / 流程"
        title="一轮出稿的流程"
        lede="从你发出一句需求，到 AI 自检通过、把画布交还给你。了解这条流程，就知道什么时候该等、什么时候该动手。"
      />

      <H2 id="steps">完整流程</H2>
      <ol className="dsteps">
        <li>
          <b>打开画布 · canvas_open</b>
          AI 绑定或新建一个画布，浏览器自动打开。一个对话同一时间只绑定一个画布，返回的 <code>canvas_id</code> 会留在对话里，下次续改时传回去。
        </li>
        <li>
          <b>问清需求 · design_ask</b>
          项目里还没有设计依据时，画布上出现需求问卷。你在对话里已经把产品、页面内容和视觉偏好说清楚的话，AI 会跳过问卷。
        </li>
        <li>
          <b>规划页面 · design_plan</b>
          AI 一次声明本轮要画的全部页面和区块，画布立即建好空画板并显示骨架屏，顶栏显示进度。
        </li>
        <li>
          <b>定设计依据</b>
          按优先级：项目的设计系统 → 本地设计规范文件 → 从三张方向卡片里选一张并存成设计系统。详见 <Link href="/docs/design-system">设计系统</Link>。
        </li>
        <li>
          <b>绘制 · node_insert / node_update</b>
          AI 光标出现在正在画的画板上，旁边显示它在做什么（比如“登录表单”）。一次插入一整块区域，节点按顺序逐个显示出来。
        </li>
        <li>
          <b>截图自检 · design_screenshot</b>
          对每张改过的画板截图，服务端附上渲染检查与设计提醒，并与上一次截图做像素对比，标出哪些区域变了（修改没生效时也会指出）。阶梯外的字号、间距、圆角可以用 design_lint_fix 一键换成令牌。报告里的问题必须修好再截图，直到没有问题。
        </li>
        <li>
          <b>补业务说明 · design_annotate</b>
          涉及多页面、交互或业务规则时，AI 在画板之间画跳转箭头、写说明框（整条流程可以写成 Mermaid，由服务端排版），这一步完成才算一轮结束。
        </li>
      </ol>

      <H2 id="lock">编辑锁：AI 画的时候你不能改</H2>
      <p>
        AI 的第一个写操作会拿到画布的编辑锁，画布变为只读，属性面板显示“AI 正在修改”。你仍然可以缩放、平移、选中查看。以下情况锁会释放：
      </p>
      <ul>
        <li>AI 改过的所有画板都完成了截图自检（规划过的页面也都开始画了）。</li>
        <li>你点了顶栏的“终止并解锁”，或 Agent 会话关闭。</li>
        <li>AI 30 秒内没有任何工具调用（规划里还有未开始的页面时放宽到 120 秒）。空闲超时只解锁，规划会暂存，AI 下次写入时恢复。</li>
      </ul>
      <Note>
        对 AI 这一轮不满意，点顶栏的“回退 AI 上一轮”，会把它一次持锁期间的全部写入整体撤回。AI 下一次动手时会收到提醒，不会原样重做被回退的内容，而是先看现状，必要时问你原因。你自己的撤销（<kbd>Ctrl</kbd>+<kbd>Z</kbd>）只回退你自己的改动。
      </Note>

      <H2 id="self-check">自检会检查什么</H2>
      <Table
        head={['类别', '内容', '是否必须修']}
        rows={[
          ['渲染', '文字溢出、元素被裁切、图片加载失败等', '是'],
          ['对比度', '按实际底色计算，正文 4.5:1、大字 3:1（禁用控件除外）', '是'],
          ['点击区域', '移动端画板上可点击元素小于 44×44', '是'],
          ['图片清晰度', '位图被放大超过 1.3 倍', '是'],
          ['交互状态', '点击、输入、计时后能到达的每个状态都重新检查；点击后控件跳动（state_shift）', '是'],
          ['交互逻辑', '永远不会出现的元素、跳到不存在的画板、未声明的变量', '是'],
          ['设计提醒', '字号 / 间距不在阶梯上、字重过多、没有视觉焦点、卡片嵌套、emoji 图标、直接写色值等', '参考'],
          ['像素对比', '再次截图时与上一张比对，列出变化区域；改过却没有任何变化时提醒修改没生效', '按需'],
        ]}
      />
      <p>
        设计提醒里阶梯外的字号、间距、圆角，以及和令牌同值的色值，AI 可以用 <code>design_lint_fix</code> 一次换成最接近的令牌（先预览改动、再写入）；相差太大的值和层级、粗体这类判断性问题仍由它逐条处理。
      </p>

      <H2 id="iterate">续改：怎么让 AI 改得准</H2>
      <h3>指着改</h3>
      <p>
        在画布上选中元素，然后对 AI 说“把我选中的按钮改成描边样式”。AI 通过 <code>canvas_status</code> 读到你的选区。
      </p>
      <h3>用评论改</h3>
      <p>
        按 <kbd>C</kbd> 在元素上放评论，写下要改的地方，然后对 AI 说“按评论改”。改好并自检后，AI 会把评论标为已解决；没改或拿不准的会保留并说明原因。
      </p>
      <h3>你先改，AI 接着改</h3>
      <p>
        你在画布上改过的边距、颜色、文字都会记录下来。AI 续改前会用 <code>design_changes</code> 查看你的手动改动，不会把它们改回去。
      </p>
      <Code lang="提示词示例" copy={false}>{`继续上次的画布，按我的评论改，改完再把首页的桌面端也画一版。
把我选中的卡片存成组件，列表里的其他卡片都换成它。
登录页加上短信验证码登录，倒计时 60 秒，能点能切换。`}</Code>

      <H2 id="rounds">新一轮迭代：另开一个画布</H2>
      <p>
        已有页面基本定稿、这一轮要画一批新页面时，AI 会在同一项目下另开一个画布（<code>canvas_open</code> 传 <code>new:true</code> 和本轮主题），新画布只放本轮的新页面。这样单个画布不会越画越大，AI 读稿更快、更省 token。只是修改已有页面时，仍然在原画布上改。
      </p>
      <ul>
        <li>新画布沿用项目的设计系统，不会再出问卷。</li>
        <li>
          新页面要跳到旧页面时用跨画布链接（写法见 <Link href="/docs/prototype#navigate">交互原型</Link>）。被链接的旧页面在画布右侧显示成只读卡片，标出所在画布和页面名称，可以点“打开所在画布”。卡片不进入设计稿和导出，批注箭头可以连到卡片上。
        </li>
        <li>AI 需要参考旧页面时只读查看，不会绑定旧画布，也不会锁住它。</li>
        <li>旧页面要改时，AI 先把它复制到新画布再改，用到的组件、图片和令牌一起带过来，旧画布保持原样。</li>
        <li>换画布前，当前画布上的改动必须都已自检完、规划的页面都已开始画。</li>
      </ul>
      <p>画布首页按项目分组，组内按创建时间列成“第 N 轮”。</p>
      <Code lang="提示词示例" copy={false}>{`这一轮加会员体系：会员中心、开通页、支付结果页，另开一个画布画，
支付结果页的“返回首页”跳到上一轮画好的首页。`}</Code>

      <H2 id="prompt">写需求的建议</H2>
      <ul>
        <li>说清产品是什么、给谁用，比如“面向自由职业者的记账 App”，比“记账 App”好得多。</li>
        <li>说清设备：移动端（390）、平板（768）还是桌面端（1440），要几端。</li>
        <li>列出页面和每页的主要内容。不确定时可以让 AI 先规划，你在骨架屏上看过再继续。</li>
        <li>有视觉偏好就直接说：风格、主色、明暗、参考产品。说了 AI 就不再出问卷。</li>
        <li>项目里已有前端代码时，说“按项目现有样式”，AI 会从 CSS 变量或 Tailwind / shadcn 主题导入设计系统。</li>
      </ul>
    </>
  );
}
